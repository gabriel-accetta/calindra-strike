"""Convert a Hammer 2.2 de_dust2 RMF into shared convex geometry.

Usage: python3 tools/maps/import-dust2.py /path/to/de_dust2.rmf
Only geometry is imported; materials are generated by Calindra Strike.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct


class Reader:
    def __init__(self, data):
        self.data = data
        self.offset = 7
        assert data[4:7] == b'RMF' and abs(struct.unpack_from('<f', data)[0] - 2.2) < 0.001
        self.offset += 4 + struct.unpack_from('<i', data, 7)[0] * 140

    def read(self, fmt):
        values = struct.unpack_from('<' + fmt, self.data, self.offset)
        self.offset += struct.calcsize('<' + fmt)
        return values[0] if len(values) == 1 else values

    def string(self):
        size = self.read('B')
        value = self.data[self.offset:self.offset + size].rstrip(b'\0').decode('latin1')
        self.offset += size
        return value

    def object(self):
        kind = self.string()
        self.offset += 7  # visgroup ID and editor colour
        children = [self.object() for _ in range(self.read('i'))]
        faces = []
        properties = {}
        if kind == 'CMapSolid':
            for _ in range(self.read('i')):
                texture = self.data[self.offset:self.offset + 260].split(b'\0')[0].decode('latin1')
                self.offset += 320  # texture, Valve UV axes, rotation, scale, surface flags
                vertices = [self.read('3f') for _ in range(self.read('i'))]
                self.offset += 36  # original editor plane points
                faces.append((texture, vertices))
        elif kind in ('CMapWorld', 'CMapEntity'):
            properties['classname'] = self.string()
            self.offset += 8
            for _ in range(self.read('i')):
                key = self.string()
                properties[key] = self.string()
            self.offset += 12
            if kind == 'CMapEntity':
                self.offset += 2
                properties['origin'] = self.read('3f')
                self.offset += 4
        elif kind != 'CMapGroup':
            raise ValueError(f'Unsupported object: {kind}')
        return kind, children, faces, properties


def material(texture):
    name = texture.lower()
    if 'crt' in name or 'crte' in name:
        return 'crate'
    if 'door' in name:
        return 'wood'
    if 'road' in name or name in ('-0sand', '-2sand'):
        return 'ground'
    return 'brick'


def convert(node, output, entity='worldspawn'):
    kind, children, raw_faces, properties = node
    entity = properties.get('classname', entity)
    if entity.startswith('trigger_') or entity in ('func_buyzone', 'func_bomb_target'):
        return
    if raw_faces and not all(t.upper() in ('SKY', 'ORIGIN', 'AAATRIGGER') for t, _ in raw_faces):
        faces = []
        for texture, raw in raw_faces:
            vertices = [[round(x, 4), round(z + 512, 4), round(-y, 4)] for x, y, z in raw]
            if len(vertices) >= 3:
                faces.append({'vertices': vertices, 'mat': material(texture)})
        vertices = [v for f in faces for v in f['vertices']]
        center = [sum(v[i] for v in vertices) / len(vertices) for i in range(3)]
        planes = []
        for face in faces:
            a, b, c = face['vertices'][:3]
            u = [b[i] - a[i] for i in range(3)]
            v = [c[i] - a[i] for i in range(3)]
            normal = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
            length = math.sqrt(sum(n*n for n in normal))
            if length < 0.001:
                continue
            normal = [n / length for n in normal]
            distance = sum(normal[i] * a[i] for i in range(3))
            if sum(normal[i] * center[i] for i in range(3)) > distance:
                normal = [-n for n in normal]
                distance = -distance
                face['vertices'].reverse()
            planes.append([*normal, distance])
        if len(planes) >= 4:
            output.append({
                'min': dict(zip(('x', 'y', 'z'), [min(v[i] for v in vertices) for i in range(3)])),
                'max': dict(zip(('x', 'y', 'z'), [max(v[i] for v in vertices) for i in range(3)])),
                'planes': planes,
                'faces': faces,
                'solid': entity != 'func_illusionary',
            })
    for child in children:
        convert(child, output, entity)


def objectives(node, result):
    kind, children, faces, props = node
    classname = props.get('classname', '')
    if classname in ('info_player_deathmatch', 'info_player_start'):
        x, y, z = props['origin']
        angle = float(props.get('angles', '0 0 0').split()[1])
        team = 0 if classname == 'info_player_deathmatch' else 1
        result['spawns'][team].append({'x': x, 'y': z + 512, 'z': -y, 'yaw': math.radians(angle) - math.pi / 2})
    if classname == 'func_bomb_target':
        vertices = []
        def collect(n):
            for _, face_vertices in n[2]:
                vertices.extend((x, z + 512, -y) for x, y, z in face_vertices)
            for child in n[1]:
                collect(child)
        collect(node)
        result['sites'].append({
            'id': 'A' if props.get('target') == 'tgt_a' else 'B',
            'min': dict(zip(('x', 'y', 'z'), [min(v[i] for v in vertices) for i in range(3)])),
            'max': dict(zip(('x', 'y', 'z'), [max(v[i] for v in vertices) for i in range(3)])),
        })
    for child in children:
        objectives(child, result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    data = args.source.read_bytes()
    brushes = []
    root = Reader(data).object()
    convert(root, brushes)
    metadata = {'spawns': [[], []], 'sites': []}
    objectives(root, metadata)
    target = Path(__file__).resolve().parents[2] / 'shared/src/maps/dust2.geometry.json'
    target.with_name('dust2.objectives.json').write_text(json.dumps(metadata, indent=2) + '\n')
    target.write_text(json.dumps(brushes, separators=(',', ':')) + '\n')
    print(f'{len(brushes)} brushes -> {target}; source SHA256: {hashlib.sha256(data).hexdigest()}')


if __name__ == '__main__':
    main()
